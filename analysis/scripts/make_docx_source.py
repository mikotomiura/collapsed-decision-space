# The source


def _div(style: str, text: str) -> str:
    return f'::: {{custom-style="{style}"}}\n{text}\n:::'


def _table_rows(lines: list[str]) -> list[list[str]]:
    rows = []
    for line in lines:
        cells = re.split(r"(?<!\\)\|", line.strip())[1:-1]
        rows.append([c.strip() for c in cells])
    return rows


def parse_author_table(
    inner: list[str], offset: int
) -> tuple[dict[str, tuple[int, str]], list[int]]:
    """The rows of the author table, label -> (1-based line, cell), and the lines left out."""
    rows: dict[str, tuple[int, str]] = {}
    dropped: list[int] = []
    for index, line in enumerate(inner):
        number = offset + index + 1
        if not line.strip():
            continue
        if line.startswith("| ") and not re.fullmatch(r"\|\s*\|\s*\|", line.strip()):
            cells = _table_rows([line])[0]
            if len(cells) != 2:
                _die(f"line {number}: an author-table row must have two cells")
            label, cell = cells
            if label not in TABLE_ROWS:
                _die(
                    f"line {number}: the author table has a row {label!r} this build does not place"
                )
            rows[label] = (number, cell)
        else:
            dropped.append(number)
    missing = TABLE_ROWS - set(rows)
    if missing:
        _die(f"the author table has no row {sorted(missing)}")
    return rows, dropped


def build(repo_root: Path, *, no_preprint: bool) -> tuple[str, dict[str, Any]]:
    manuscript = repo_root / "manuscript" / "main.md"
    text = manuscript.read_text(encoding="utf-8")
    lines = text.split("\n")
    cff = read_citation_cff(repo_root / "CITATION.cff")
    doi = preprint_doi(cff, no_preprint=no_preprint)
    references = parse_references(text)

    if not lines[0].startswith("# "):
        _die("the first line of main.md is not the level-one heading")
    title = lines[0][2:].strip()
    if title != cff.get("title"):
        _die("the title of main.md is not the title of CITATION.cff")

    drop_begin, drop_end = lines.index(DROP_BEGIN), lines.index(DROP_END)
    if any(line.strip() for line in lines[1:drop_begin]):
        _die("the TMLR:DROP block must follow the title directly")
    rows, dropped_lines = parse_author_table(lines[drop_begin + 1 : drop_end], drop_begin + 1)

    abstract_head = lines.index("## Abstract", drop_end)
    abstract_end = lines.index("---", abstract_head)
    abstract = " ".join(" ".join(lines[abstract_head + 1 : abstract_end]).split())
    if abstract != " ".join(str(cff.get("abstract", "")).split()):
        _die("the abstract of main.md is not the abstract of CITATION.cff")

    blocks = cut_blocks(lines, abstract_end + 1)
    offsets = [0]
    for line in lines:
        offsets.append(offsets[-1] + len(line) + 1)
    regions = [
        (offsets[b.start], offsets[b.end])
        for b in blocks
        if b.kind in ("para", "item", "heading", "table", "figure")
    ]
    cites = find_citations(text, regions, references)
    for block in blocks:
        if block.kind in ("table", "figure") and any(
            offsets[block.start] <= c.start < offsets[block.end] for c in cites
        ):
            # Their labels and titles are set above them, so a citation in them would be out of the
            # order citeproc and the check number citations in.
            _die(
                f"line {block.start + 1}: a citation in a table or a figure caption is not handled"
            )
    check_against_tmlr_fixture(repo_root, cites)
    cited = {n for c in cites for n in c.ids}
    uncited = sorted({r.number for r in references} - cited)
    if uncited:
        _die(f"the References section lists entries nothing cites: {uncited}")

    def with_citations(block: Block) -> str:
        """The block's text with each citation in it replaced by its pandoc markup."""
        a, b = offsets[block.start], offsets[block.end] - 1
        own = [c for c in cites if a <= c.start < b]
        if any(c.end > b for c in own):
            _die(f"a citation runs past the block at line {block.start + 1}")
        out, cursor = [], a
        for cite in own:
            out.append(text[cursor : cite.start])
            out.append(citation_markup(cite))
            cursor = cite.end
        out.append(text[cursor:b])
        return "".join(out)

    record: dict[str, Any] = {
        "source": "manuscript/main.md",
        "source_sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
        "citations": [
            {
                "k": c.k,
                "line": c.line,
                "ids": list(c.ids),
                "kind": c.kind,
                "removed": c.removed,
                "prefix": c.prefix,
                "suffix": c.suffix,
            }
            for c in cites
        ],
        "head": {
            "title": title,
            "author": rows["Author"][1],
            "affiliation": rows["Affiliation"][1],
            "abstract_lines": [abstract_head + 2, abstract_end],
            "keywords": list(cff.get("keywords", [])),
            "preprint_doi": doi,
        },
        "author_note": [],
        "figures": [],
        "tables": [],
        "drops": [],
        "bibliography": {
            "lines": [],
            "ids": [r.number for r in references],
        },
        "page_breaks": [],
    }
    record["drops"].append({"what": "author table, left out", "lines": dropped_lines})

    out: list[str] = []
    out.append(_div("Title", title))
    out.append(_div("Author", rows["Author"][1]))
    out.append(_div("Affiliation", rows["Affiliation"][1]))
    out.append(_div("Author Note Heading", "Author Note"))
    for label in NOTE_ROWS_BEFORE:
        number, cell = rows[label]
        out.append(_div("Author Note", f"{label}: {cell}"))
        record["author_note"].append({"what": label, "lines": [number, number]})
    if doi is not None:
        # The one sentence of the title page this script writes: the identifier is a fact of the
        # archive, and the sentence states only that the preprint is of an earlier version.
        out.append(
            _div(
                "Author Note",
                f"Preprint: an earlier version is available at https://doi.org/{doi}.",
            )
        )
        record["author_note"].append({"what": "Preprint", "lines": []})

    ai = [b for b in blocks if b.kind == "footnote"]
    if len(ai) != 1:
        _die("main.md must carry exactly one TMLR:FOOTNOTE block")
    ai_text = "\n".join(ai[0].lines).strip()
    if not ai_text:
        _die("the TMLR:FOOTNOTE block is empty")
    out.append(_div("Author Note", ai_text))
    record["author_note"].append(
        {"what": "AI disclosure", "lines": [ai[0].start + 2, ai[0].end - 1]}
    )
    for label in NOTE_ROWS_AFTER:
        number, cell = rows[label]
        out.append(_div("Author Note", f"{label}: {cell}"))
        record["author_note"].append({"what": label, "lines": [number, number]})

    out.append(_div("Abstract Title", "Abstract"))
    out.append(_div("Abstract", "\n".join(lines[abstract_head + 1 : abstract_end]).strip()))
    keywords = cff.get("keywords") or []
    if not keywords:
        _die("CITATION.cff carries no keywords")
    out.append(_div("Keywords", "*Keywords:* " + ", ".join(keywords)))
    out.append(_div("Title Repeat", title))

    table_number = 0
    figure_number = 0
    appendix = False
    previous: Block | None = None
    for block in blocks:
        span = [block.start + 1, block.end]
        # An item that follows another with no blank line between them in main.md continues the same
        # tight list, so it is joined to it with a single line break rather than a blank line.
        joined = (
            block.kind == "item"
            and previous is not None
            and previous.kind == "item"
            and previous.end == block.start
        )
        previous = block
        if joined:
            out[-1] += "\n" + with_citations(block)
            continue
        if block.kind == "footnote":
            record["drops"].append(
                {"what": "AI disclosure, moved to the Author Note", "lines": span}
            )
        elif block.kind == "marker":
            if block.name == APPENDIX:
                appendix = True
            elif not PLAIN_MARKERS.match(block.name):
                _die(f"line {block.start + 1}: a marker this build does not know: {block.name}")
            record["drops"].append({"what": "marker", "lines": span, "text": block.name})
        elif block.kind == "rule":
            record["drops"].append({"what": "rule", "lines": span})
        elif block.kind == "references":
            record["bibliography"]["lines"] = span
            out.append("::: {#refs}\n:::")
        elif block.kind == "note":
            record["drops"].append(
                {
                    "what": "note after the references",
                    "lines": span,
                    "text": " ".join(" ".join(block.lines).split()),
                }
            )
        elif block.kind == "heading":
            heading = block.lines[0]
            if heading == "## References" or (appendix and re.match(r"^## [A-Z]\. ", heading)):
                out.append(PAGE_BREAK)
                record["page_breaks"].append(block.start + 1)
            out.append(heading)
        elif block.kind == "figure":
            figure_number += 1
            caption = "\n".join(block.lines).strip()
            label = CAPTION_LABEL.match(caption)
            if not label or int(label.group(1)) != figure_number:
                _die(
                    f"figure {block.name} is not labelled Figure {figure_number} in order of appearance"
                )
            body = with_citations(block)
            body = body[body.index("**Figure") :].replace(FIGURE_END, "").strip()
            body = CAPTION_LABEL.sub("", body, count=1)
            out.append(_div("Figure Number", f"Figure {figure_number}"))
            out.append(_div("Figure Title", body))
            out.append(_div("Figure Image", f"![](figs/fig-{block.name}.png)"))
            record["figures"].append({"number": figure_number, "name": block.name, "lines": span})
        elif block.kind == "table":
            table_number += 1
            source = with_citations(block)
            table_lines = source.split("\n")[: len(block.lines)]
            caption = "\n".join(source.split("\n")[block.caption_start - block.start :]).strip()
            caption = caption.removeprefix("Table: ").strip()
            weighted, _ = weight_table_columns("\n".join(table_lines))
            out.append(_div("Table Number", f"Table {table_number}"))
            out.append(_div("Table Title", caption))
            out.append(weighted)
            record["tables"].append(
                {
                    "number": table_number,
                    "lines": [block.start + 1, block.start + len(block.lines)],
                    "caption_line": block.caption_start + 1,
                }
            )
        elif block.kind in ("para", "item"):
            out.append(with_citations(block))
        elif block.kind == "code":
            out.append("\n".join(block.lines))
        else:
            _die(f"line {block.start + 1}: unhandled block {block.kind}")
    if not record["bibliography"]["lines"]:
        _die("main.md has no rendered reference list")
    if figure_number == 0 or table_number == 0:
        _die("the manuscript carries no figure or no table")

    return "\n\n".join(out) + "\n", record


