W = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"
R = "http://schemas.openxmlformats.org/officeDocument/2006/relationships"

#: Times New Roman 12, double-spaced, no space between paragraphs (APA 7, 2.19 to 2.24). Set as
#: defaults rather than on Normal, so that a table style can set its own size and spacing.
DOC_DEFAULTS = (
    "<w:docDefaults><w:rPrDefault><w:rPr>"
    '<w:rFonts w:ascii="Times New Roman" w:hAnsi="Times New Roman" w:eastAsia="Times New Roman" '
    'w:cs="Times New Roman"/><w:sz w:val="24"/><w:szCs w:val="24"/>'
    '<w:lang w:val="en-US" w:eastAsia="en-US" w:bidi="ar-SA"/></w:rPr></w:rPrDefault>'
    '<w:pPrDefault><w:pPr><w:spacing w:before="0" w:after="0" w:line="480" w:lineRule="auto"/>'
    "</w:pPr></w:pPrDefault></w:docDefaults>"
)


def _pstyle(
    style_id: str,
    name: str,
    ppr: str = "",
    rpr: str = "",
    based: str = "Normal",
    custom: bool = True,
    extra: str = "",
) -> str:
    flag = ' w:customStyle="1"' if custom else ""
    return (
        f'<w:style w:type="paragraph"{flag} w:styleId="{style_id}"><w:name w:val="{name}"/>'
        f'<w:basedOn w:val="{based}"/>{extra}<w:qFormat/>'
        f"<w:pPr>{ppr}</w:pPr><w:rPr>{rpr}</w:rPr></w:style>"
    )


def _cstyle(style_id: str, name: str, rpr: str) -> str:
    return (
        f'<w:style w:type="character" w:customStyle="1" w:styleId="{style_id}"><w:name w:val="{name}"/>'
        f'<w:basedOn w:val="DefaultParagraphFont"/><w:rPr>{rpr}</w:rPr></w:style>'
    )


INDENT = '<w:ind w:firstLine="720"/>'
NO_INDENT = '<w:ind w:firstLine="0"/>'
CENTER = '<w:jc w:val="center"/>'
BOLD = "<w:b/><w:bCs/>"
ITALIC = "<w:i/><w:iCs/>"
KEEP = "<w:keepNext/>"
SINGLE = '<w:spacing w:line="240" w:lineRule="auto"/>'

