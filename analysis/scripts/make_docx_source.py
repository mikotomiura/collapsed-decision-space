DROP_BEGIN = "<!-- TMLR:DROP -->"
DROP_END = "<!-- /TMLR:DROP -->"
FOOTNOTE_BEGIN = "<!-- TMLR:FOOTNOTE -->"
FOOTNOTE_END = "<!-- /TMLR:FOOTNOTE -->"
APPENDIX = "<!-- TMLR:APPENDIX -->"
FIGURE_BEGIN = re.compile(r"^<!-- TMLR:FIGURE ([a-z0-9-]+) -->$")
FIGURE_END = "<!-- /TMLR:FIGURE -->"
REFS_BEGIN = "<!-- BEGIN RENDERED FROM manuscript/refs.json -- DO NOT EDIT BY HAND -->"
REFS_END = "<!-- END RENDERED FROM manuscript/refs.json -->"
#: Markers that carry nothing for the ``.docx`` and are left out where they stand.
PLAIN_MARKERS = re.compile(
    r"^<!-- (?:REPORTED-BRANCH: \S+|BEGIN GENERATED FROM \S+ -- DO NOT EDIT BY HAND|"
    r"END GENERATED FROM \S+) -->$"
)
CAPTION_LABEL = re.compile(r"^\*\*Figure (\d+)\.\*\*\s+")

#: The rows of the author table and where each goes. Every row must be one of these: a row this
#: script does not place would otherwise be dropped without a word.
TITLE_ROWS: tuple[str, ...] = ("Author", "Affiliation")
NOTE_ROWS_BEFORE: tuple[str, ...] = ("ORCID", "Protocol status", "Code and data", "License")
NOTE_ROWS_AFTER: tuple[str, ...] = ("Correspondence",)
TABLE_ROWS = frozenset(TITLE_ROWS + NOTE_ROWS_BEFORE + NOTE_ROWS_AFTER)

#: The description an identifier of ``CITATION.cff`` must open with to name the preprint of an
#: earlier version, which the Author Note then declares (design-final §3.5).
PREPRINT_DESCRIPTION = "Preprint of an earlier version"

#: A paragraph that starts a new page and takes no room on it: an empty paragraph in the style
#: ``Page Break`` of the reference document, which breaks the page before itself and is one point
#: high. pandoc passes the raw block through as it is.
PAGE_BREAK = '```{=openxml}\n<w:p><w:pPr><w:pStyle w:val="PageBreak"/></w:pPr></w:p>\n```'

CITATION_STYLE = "Citation"


def _die(message: str) -> None:
    print(f"[docx-source] {message}", file=sys.stderr)
    raise SystemExit(1)


def verify_vendored(repo_root: Path) -> int:
    """Require the vendored citation style to be the bytes ``manuscript/docx/VENDORED.json`` records.

    The reference list is APA 7 only while the style is the APA style as published; a local edit to
    it would still set a reference list that looks like one.
    """
    directory = repo_root / "manuscript" / "docx"
    record = json.loads((directory / "VENDORED.json").read_text(encoding="utf-8"))
    for name, digest in record["sha256"].items():
        actual = hashlib.sha256((directory / name).read_bytes()).hexdigest()
        if actual != digest:
            _die(
                f"manuscript/docx/{name} is not the vendored file VENDORED.json records ({actual[:12]})"
            )
    return len(record["sha256"])


