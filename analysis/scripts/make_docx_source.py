def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parents[2])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--out-dir", type=Path, help="write paper-source.md and contract.json here")
    mode.add_argument("--reference-docx", type=Path, help="pandoc's default reference.docx")
    mode.add_argument(
        "--standalone-figures", type=Path, help="the directory make_figures.py wrote to"
    )
    mode.add_argument(
        "--figure-manifest", type=Path, help="the directory holding the figures' PNGs"
    )
    parser.add_argument("--out", type=Path, help="with --reference-docx: where to write it")
    parser.add_argument(
        "--no-preprint",
        action="store_true",
        help="no preprint of this work is public, so the Author Note declares none (record why)",
    )
    args = parser.parse_args(argv)

    if args.reference_docx:
        if not args.out:
            parser.error("--reference-docx needs --out")
        data = make_reference_docx(args.reference_docx.read_bytes())
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_bytes(data)
        print(
            f"[docx-source] wrote {args.out} ({len(data)} bytes, sha256 {hashlib.sha256(data).hexdigest()[:16]})"
        )
        return 0
    if args.standalone_figures:
        names = write_standalone(args.repo_root, args.standalone_figures)
        print(f"[docx-source] wrote the standalone sources of {', '.join(names)}")
        return 0
    if args.figure_manifest:
        manifest = write_manifest(args.repo_root, args.figure_manifest)
        print(f"[docx-source] recorded {len(manifest['figures'])} figure PNGs in figures.json")
        return 0

    vendored = verify_vendored(args.repo_root)
    print(f"[docx-source] the {vendored} vendored citation style file matches VENDORED.json")
    source, record = build(args.repo_root, no_preprint=args.no_preprint)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "paper-source.md").write_text(source, encoding="utf-8", newline="\n")
    (args.out_dir / "contract.json").write_text(
        json.dumps(record, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n"
    )
    kinds = {
        k: sum(1 for c in record["citations"] if c["kind"] == k)
        for k in ("parenthetical", "narrative", "in-parentheses")
    }
    print(
        f"[docx-source] {len(record['citations'])} citations {kinds}, {len(record['figures'])} figures, "
        f"{len(record['tables'])} tables, {len(record['author_note'])} Author Note paragraphs, "
        f"{len(record['drops'])} items left out, {len(record['page_breaks'])} page breaks; "
        f"preprint {'declared' if record['head']['preprint_doi'] else 'none (--no-preprint)'}"
    )
    print(f"[docx-source] wrote {args.out_dir}/paper-source.md and contract.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
