# Citations


@dataclass
class Citation:
    k: int
    line: int  # 1-based line of the marker in main.md
    ids: tuple[int, ...]
    kind: str  # parenthetical, narrative, in-parentheses
    removed: str  # the authors' names the prose wrote by hand, for a narrative citation
    prefix: str  # for a citation inside a parenthesis
    suffix: str
    context: str  # the last four words before the marker, as manuscript/tmlr/citations.tsv has it
    mode: str  # citep / citeyearpar, as manuscript/tmlr/citations.tsv has it
    start: int  # offsets into the whole text of what the citation replaces
    end: int


def _paren_depth(text: str) -> int:
    return text.count("(") - text.count(")")


def find_citations(text: str, regions: list[tuple[int, int]], references: Any) -> list[Citation]:
    """Every ``[n]`` marker in ``regions`` of ``text``, outside code, with its kind and extent."""
    by_number = {r.number: r for r in references}
    shielded = _shielded_spans(text)
    out: list[Citation] = []
    for match in _CITE.finditer(text):
        if not any(a <= match.start() < b for a, b in regions):
            continue
        if any(a <= match.start() < b for a, b in shielded):
            continue
        ids = tuple(int(n) for n in match.group(1).split(", "))
        unknown = [n for n in ids if n not in by_number]
        if unknown:
            _die(f"citation [{match.group(1)}] names no entry of the References section: {unknown}")
        before = " ".join(text[max(0, match.start() - 120) : match.start()].split()) + " "
        mode, form = "citep", ""
        if len(ids) == 1:
            for candidate in _textual_forms(by_number[ids[0]]):
                if before.endswith(" " + candidate + " ") or before.endswith("*" + candidate + " "):
                    mode, form = "citeyearpar", candidate
                    break
        context = " ".join(before.split()[-4:])
        line = text.count("\n", 0, match.start()) + 1
        paragraph_start = text.rfind("\n\n", 0, match.start()) + 2
        # Code spans are blanked, not removed, so that an offset into ``lead`` is one into the text.
        lead = re.sub(
            r"`[^`\n]*`", lambda m: "x" * len(m.group(0)), text[paragraph_start : match.start()]
        )
        start, end, prefix, suffix, kind = match.start(), match.end(), "", "", "parenthetical"
        if form:
            words = r"\s+".join(re.escape(w) for w in form.split())
            found = re.search(
                r"(?<=[\s*])" + words + r"\s+$", text[paragraph_start : match.start()]
            )
            if not found:
                _die(f"line {line}: cannot find the names {form!r} before the marker")
            start = paragraph_start + found.start()
            kind = "narrative"
        if _paren_depth(lead) > 0:
            if form:
                _die(f"line {line}: a narrative citation inside a parenthesis is not handled")
            opening = paragraph_start + lead.rfind("(")
            # Only the innermost open parenthesis is read; a nested one is not handled.
            if _paren_depth(lead[lead.rfind("(") + 1 :]) != 0:
                _die(f"line {line}: a citation inside nested parentheses is not handled")
            depth, close = 1, match.end()
            while close < len(text) and depth:
                if text[close] == "(":
                    depth += 1
                elif text[close] == ")":
                    depth -= 1
                close += 1
            if depth:
                _die(f"line {line}: the parenthesis around the citation is never closed")
            prefix = " ".join(text[opening + 1 : match.start()].split())
            suffix = " ".join(text[match.end() : close - 1].split())
            if "@" in prefix + suffix or ";" in prefix + suffix or "[" in prefix + suffix:
                _die(
                    f"line {line}: the text around the citation cannot be a citation's prefix or suffix"
                )
            start, end, kind = opening, close, "in-parentheses"
        out.append(
            Citation(len(out) + 1, line, ids, kind, form, prefix, suffix, context, mode, start, end)
        )
    return out


def citation_markup(cite: Citation) -> str:
    keys = "; ".join(f"@cds{n}" for n in cite.ids)
    if cite.kind == "narrative":
        inner = keys
    elif cite.kind == "in-parentheses":
        inner = f"[{cite.prefix} {keys} {cite.suffix}]"
    else:
        inner = f"[{keys}]"
    return f'[{inner}]{{custom-style="{CITATION_STYLE}"}}'


def check_against_tmlr_fixture(repo_root: Path, cites: list[Citation]) -> None:
    """The kinds and identifiers must be those ``make_pdf_source.py`` records, row for row."""
    path = repo_root / "manuscript" / "tmlr" / "citations.tsv"
    rows = [r.split("\t") for r in path.read_text(encoding="utf-8").splitlines()[1:]]
    mine = [[c.context, ", ".join(map(str, c.ids)), c.mode] for c in cites]
    if rows != mine:
        for k, (want, have) in enumerate(zip(rows, mine, strict=False), start=1):
            if want != have:
                _die(f"citation {k}: {path.name} has {want}, this build reads {have}")
        _die(f"{path.name} has {len(rows)} citations, this build reads {len(mine)}")


