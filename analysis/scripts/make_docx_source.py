# Figures

#: The figure as the PDF sets it: ``make_figures.py``'s TikZ in the TMLR text width and fonts, at
#: ``\small``, with the glyph-to-Unicode map so that its numbers read back as text.
STANDALONE = r"""\documentclass[border=4pt]{standalone}
\usepackage[T1]{fontenc}
\usepackage{lmodern}
\usepackage{amsmath,amssymb}
\usepackage{tikz}
\usetikzlibrary{patterns,positioning}
\input{glyphtounicode}
\pdfgentounicode=1
\setlength{\textwidth}{6.5in}
\begin{document}
{\small\input{fig-NAME}}
\end{document}
"""


def figure_names(repo_root: Path) -> list[str]:
    text = (repo_root / "manuscript" / "main.md").read_text(encoding="utf-8")
    return [m.group(1) for m in re.finditer(r"^<!-- TMLR:FIGURE ([a-z0-9-]+) -->$", text, re.M)]


def write_standalone(repo_root: Path, directory: Path) -> list[str]:
    names = figure_names(repo_root)
    for name in names:
        if not (directory / f"fig-{name}.tex").is_file():
            _die(
                f"{directory}/fig-{name}.tex is missing; run make_figures.py --out-dir {directory}"
            )
        (directory / f"fig-{name}-standalone.tex").write_text(
            STANDALONE.replace("NAME", name), encoding="utf-8", newline="\n"
        )
    return names


def write_manifest(repo_root: Path, directory: Path) -> dict[str, Any]:
    figures = []
    for number, name in enumerate(figure_names(repo_root), start=1):
        png = directory / f"fig-{name}.png"
        if not png.is_file():
            _die(f"{png} is missing")
        figures.append(
            {
                "number": number,
                "name": name,
                "png": png.name,
                "sha256": hashlib.sha256(png.read_bytes()).hexdigest(),
            }
        )
    if len({f["sha256"] for f in figures}) != len(figures):
        _die("two figures have the same PNG")
    manifest = {"figures": figures}
    (directory / "figures.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n"
    )
    return manifest


