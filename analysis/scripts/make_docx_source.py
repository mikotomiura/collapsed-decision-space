# CITATION.cff, read without a YAML library (the build runs on the system python3)


def _unquote(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] == '"':
        return value[1:-1].replace('\\"', '"').replace("\\\\", "\\")
    if len(value) >= 2 and value[0] == value[-1] == "'":
        return value[1:-1].replace("''", "'")
    return value


def read_citation_cff(path: Path) -> dict[str, Any]:
    """The fields of ``CITATION.cff`` the title page needs, read from the file's own layout.

    Only the shapes this file uses are understood -- a quoted or plain scalar, a folded block
    (``>-``), a list of scalars and a list of mappings -- and anything else under a key read here is
    an error rather than a guess. ``check_docx_text.py`` reads the same file with a YAML parser, so
    a misreading here is caught there.
    """
    lines = path.read_text(encoding="utf-8").splitlines()
    out: dict[str, Any] = {}
    index = 0
    while index < len(lines):
        line = lines[index]
        if not line.strip() or line.lstrip().startswith("#") or line.startswith(" "):
            index += 1
            continue
        match = re.match(r"^([A-Za-z][\w-]*):(?:\s+(.*))?$", line)
        if not match:
            _die(f"CITATION.cff: cannot read the line {line!r}")
        key, value = match.group(1), (match.group(2) or "").strip()
        index += 1
        block: list[str] = []
        while index < len(lines) and (lines[index].startswith(" ") or not lines[index].strip()):
            block.append(lines[index])
            index += 1
        while block and not block[-1].strip():
            block.pop()
        if value == ">-":
            paragraphs: list[list[str]] = [[]]
            for raw in block:
                if raw.strip():
                    paragraphs[-1].append(raw.strip())
                else:
                    paragraphs.append([])
            out[key] = "\n".join(" ".join(p) for p in paragraphs if p)
        elif value:
            if block:
                _die(f"CITATION.cff: {key} has a value and an indented block")
            out[key] = _unquote(value)
        else:
            items: list[Any] = []
            for raw in block:
                if raw.lstrip().startswith("#"):
                    continue
                item = re.match(r"^\s+- (.*)$", raw)
                if item:
                    pair = re.match(r"^([A-Za-z][\w-]*):\s+(.*)$", item.group(1))
                    items.append(
                        {pair.group(1): _unquote(pair.group(2))}
                        if pair
                        else _unquote(item.group(1))
                    )
                    continue
                pair = re.match(r"^\s+([A-Za-z][\w-]*):\s+(.*)$", raw)
                if pair and items and isinstance(items[-1], dict):
                    items[-1][pair.group(1)] = _unquote(pair.group(2))
                    continue
                _die(f"CITATION.cff: cannot read the line {raw!r} under {key}")
            out[key] = items
    return out


def preprint_doi(cff: dict[str, Any], *, no_preprint: bool) -> str | None:
    """The DOI of the preprint the Author Note declares, chosen by the type of its description.

    Exactly one identifier must name it. None is allowed only with ``--no-preprint``, which states
    as a fact of the build that no preprint of this work is public; it is not a way around the check
    (design-final §3.5).
    """
    found = [
        item
        for item in cff.get("identifiers", []) or []
        if isinstance(item, dict)
        and str(item.get("description", "")).startswith(PREPRINT_DESCRIPTION)
    ]
    if any(item.get("type") != "doi" for item in found):
        _die("CITATION.cff: an identifier described as a preprint is not a DOI")
    if len(found) > 1:
        _die(f"CITATION.cff names {len(found)} preprints; the Author Note declares one")
    if not found:
        if no_preprint:
            return None
        _die(
            "CITATION.cff names no preprint. If none is public, build with --no-preprint and record "
            "why; if one is, add it to CITATION.cff"
        )
    if no_preprint:
        _die("--no-preprint was given, but CITATION.cff names a preprint")
    return str(found[0]["value"])


