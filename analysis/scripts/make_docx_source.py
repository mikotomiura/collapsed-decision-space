# The manuscript, cut into blocks with their line numbers


@dataclass
class Block:
    kind: str  # heading, para, item, code, table, figure, marker, rule, footnote, references, note, blank
    start: int  # 0-based index of the first line
    end: int  # one past the last line
    lines: list[str] = field(default_factory=list)
    name: str = ""  # a figure's name, a marker's text
    caption: list[str] = field(default_factory=list)  # a table's caption lines
    caption_start: int = -1


def _is_marker(line: str) -> bool:
    return line.startswith("<!--") and line.rstrip().endswith("-->")


def cut_blocks(lines: list[str], start: int) -> list[Block]:
    """Cut ``lines[start:]`` into blocks. Fails on anything it does not recognise."""
    blocks: list[Block] = []
    i = start
    n = len(lines)
    while i < n:
        line = lines[i]
        stripped = line.strip()
        if not stripped:
            i += 1
            continue
        if _is_marker(stripped):
            figure = FIGURE_BEGIN.match(stripped)
            if stripped == FOOTNOTE_BEGIN:
                j = lines.index(FOOTNOTE_END, i)
                blocks.append(Block("footnote", i, j + 1, lines[i + 1 : j]))
                i = j + 1
            elif figure:
                j = lines.index(FIGURE_END, i)
                blocks.append(Block("figure", i, j + 1, lines[i + 1 : j], name=figure.group(1)))
                i = j + 1
            elif stripped == REFS_BEGIN:
                j = lines.index(REFS_END, i)
                blocks.append(Block("references", i, j + 1, lines[i : j + 1]))
                i = j + 1
                # The note that follows the list, up to the appendix marker.
                while i < n and not lines[i].strip():
                    i += 1
                k = i
                while k < n and lines[k].strip():
                    k += 1
                if i == k:
                    _die("no note follows the rendered reference list")
                blocks.append(Block("note", i, k, lines[i:k]))
                i = k
            else:
                blocks.append(Block("marker", i, i + 1, [line], name=stripped))
                i += 1
            continue
        if stripped == "---":
            blocks.append(Block("rule", i, i + 1, [line]))
            i += 1
            continue
        if stripped.startswith("```"):
            j = i + 1
            while j < n and not lines[j].strip().startswith("```"):
                j += 1
            if j == n:
                _die(f"a fenced code block opened at line {i + 1} is never closed")
            blocks.append(Block("code", i, j + 1, lines[i : j + 1]))
            i = j + 1
            continue
        if line.startswith("#"):
            blocks.append(Block("heading", i, i + 1, [line]))
            i += 1
            continue
        if stripped.startswith("|"):
            j = i
            while j < n and lines[j].strip().startswith("|"):
                j += 1
            block = Block("table", i, j, lines[i:j])
            k = j
            while k < n and not lines[k].strip():
                k += 1
            if k < n and lines[k].startswith("Table: "):
                m = k
                while m < n and lines[m].strip():
                    m += 1
                block.caption = lines[k:m]
                block.caption_start = k
                block.end = m
                j = m
            else:
                _die(f"the table at line {i + 1} has no 'Table:' caption")
            blocks.append(block)
            i = j
            continue
        if re.match(r"^(?:[-+*]|\d+\.) ", line):
            j = i + 1
            while j < n and lines[j].startswith("  ") and lines[j].strip():
                j += 1
            blocks.append(Block("item", i, j, lines[i:j]))
            i = j
            continue
        j = i + 1
        while (
            j < n
            and lines[j].strip()
            and not _is_marker(lines[j].strip())
            and not lines[j].startswith("#")
            and not lines[j].strip().startswith(("|", "```"))
            and not re.match(r"^(?:[-+*]|\d+\.) ", lines[j])
        ):
            j += 1
        blocks.append(Block("para", i, j, lines[i:j]))
        i = j
    return blocks


