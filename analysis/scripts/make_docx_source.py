#!/usr/bin/env python3
"""Build the pandoc source of the APA 7 ``.docx`` from ``manuscript/main.md``, and record what changed.

**There is still no second manuscript.** The ``.docx`` is the second form derived from
``manuscript/main.md``, beside the PDF of ``make_pdf_source.py``, and like it, it is derived by a
small, mechanical, deterministic transformation and read back (``check_docx_text.py``). This
script performs the transformation and writes down every change it makes, in a record of the
conversion (``contract.json``). The check enumerates the same changes from the inputs on its own,
requires the two lists to agree, checks each change against the ``.docx``, and compares the rest
of the text word for word.

What it changes, and why each change is necessary:

1. **The title page replaces the repository's author table.** The level-one heading becomes the
   title; the author and affiliation rows of the table between the ``TMLR:DROP`` markers become the
   byline; and the rows ORCID, Protocol status, Code and data, License and Correspondence become the
   paragraphs of the Author Note, each as ``Label: cell``, verbatim. The bold lead paragraph of that
   block and its closing rule are left out, as the PDF leaves them out. No sentence of the title page
   is written here: every one comes from ``main.md`` or ``CITATION.cff``.
2. **The AI disclosure moves to the Author Note.** The block between the ``TMLR:FOOTNOTE`` markers
   is moved, not copied: the ``.docx`` carries it once, in the Author Note, as the PDF carries it
   once, as a footnote. §K stays an appendix.
3. **The abstract gets its own page**, with the keywords of ``CITATION.cff`` below it, and the title
   is repeated at the top of the first page of text, as APA 7 sets a paper.
4. **Citations become APA author-date citations**, set by pandoc's citeproc with the APA 7 style
   (``manuscript/docx/apa.csl``, vendored). ``[n]`` is a permanent identifier from the central
   bibliography and ``manuscript/refs.json`` holds each entry. Three kinds are handled, and each is
   classified the same way ``make_pdf_source.py`` classifies it (``manuscript/tmlr/citations.tsv``
   is the common record of identifiers and kinds):

   * a parenthetical citation, ``[35, 36, 44]``, becomes one cluster;
   * a narrative citation, where the prose names the authors before the marker (``Hoenig and
     Heisey [44]``), loses the hand-written names, and citeproc sets them with the year
     (``Hoenig and Heisey (2001)``); the names taken out are recorded;
   * a citation inside a parenthesis, ``(§2.3, and [44] on why ...)``, becomes the cluster, with the
     text of the parenthesis as its prefix and suffix, so that the parentheses are not nested.

   Each citation is set in the character style ``Citation``, which changes nothing on the page and
   lets the check find every citation in the ``.docx``. What citeproc set for each is held in
   ``manuscript/docx/citations-apa.tsv``.
5. **The References section becomes the APA reference list**, generated by citeproc from
   ``manuscript/refs.json``, where the rendered block stands. The note after it, on the permanent
   reference numbers, is left out: the ``.docx`` prints no numbers, so it would say nothing.
6. **Figures and tables get APA labels**: a line "Figure N" or "Table N" and a line with the title,
   both above. The figure's title is its caption in ``main.md`` without the label "**Figure N.**";
   the table's is the text of its ``Table:`` line. Tables are numbered in order of appearance. A
   figure is the PNG of the figure ``make_figures.py`` draws from the shipped data, set as a
   standalone PDF and rasterised at 600 dpi.
7. **The references and each appendix begin on a new page**, and the markers in HTML comments and
   the horizontal rules are left out.

Everything else is passed through byte for byte, including the section numbers, which the
repository cites.

The script also writes the two inputs pandoc needs that are not text: the reference document that
carries the APA page and paragraph styles (generated from pandoc's own default, so that a style
change is a diff of this file), and the standalone sources of the figures.

Usage:
    python analysis/scripts/make_docx_source.py --out-dir build/docx --no-preprint
    python analysis/scripts/make_docx_source.py --reference-docx default.docx --out build/docx/reference.docx
    python analysis/scripts/make_docx_source.py --standalone-figures build/docx/figs
    python analysis/scripts/make_docx_source.py --figure-manifest build/docx/figs
"""

